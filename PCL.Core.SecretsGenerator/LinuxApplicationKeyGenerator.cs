using System;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace PCL.Core.SecretsGenerator;

// Only the redistributable application key is allowed into the Linux binary.
// Encoding reduces accidental plain-text exposure; it is not encryption.
[Generator(LanguageNames.CSharp)]
public sealed class LinuxApplicationKeyGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var key = context.CompilationProvider.Select(static (_, _) =>
        {
#pragma warning disable RS1035
            return Environment.GetEnvironmentVariable("PCL_WRITE_SECRET") == "1"
                ? Environment.GetEnvironmentVariable("PCL_CURSEFORGE_API_KEY")
                : null;
#pragma warning restore RS1035
        });
        context.RegisterSourceOutput(key, static (output, value) =>
        {
            var bytes = Encoding.UTF8.GetBytes(value ?? "");
            var source = "// <auto-generated />\n#nullable enable\nnamespace PCL.Linux.Cli;\n"
                + "internal static partial class LinuxSecrets\n{\n"
                + "    internal static string? CurseForgeApiKey { get; } = Decode(new byte[] { "
                + string.Join(", ", bytes.Select(item => (item ^ 0xA7).ToString(System.Globalization.CultureInfo.InvariantCulture)))
                + " });\n}\n";
            output.AddSource("LinuxApplicationKey.g.cs", SourceText.From(source, Encoding.UTF8));
        });
    }
}
